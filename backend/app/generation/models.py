"""Internal data structures for evidence formatting, LLM generation, and validation."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date

from app.schemas.documents import ContentType, DocumentType, ExtractionMethod
from app.schemas.query import CitationItem, ConflictItem


@dataclass(slots=True)
class EvidenceBlock:
    """Bounded, numbered evidence context unit prepared for grounded generation."""

    evidence_id: str  # e.g., "E1", "E2"
    chunk_id: str
    doc_id: str
    doc_title: str
    doc_type: DocumentType
    version: str
    effective_date: date | None
    jurisdiction: str
    project_id: str | None
    standard_code: str | None = None
    section_id: str | None = None
    section_path: list[str] = field(default_factory=list)
    page_start: int = 1
    page_end: int = 1
    content_type: ContentType = ContentType.PROSE
    extraction_method: ExtractionMethod = ExtractionMethod.NATIVE
    retrieval_score: float = 0.0
    text_verbatim: str = ""

    def to_citation_item(self) -> CitationItem:
        """Convert this evidence block into a public CitationItem contract."""
        return CitationItem(
            evidence_id=self.evidence_id,
            chunk_id=self.chunk_id,
            doc_id=self.doc_id,
            doc_title=self.doc_title,
            doc_type=self.doc_type,
            version=self.version,
            effective_date=self.effective_date,
            jurisdiction=self.jurisdiction,
            project_id=self.project_id,
            section_id=self.section_id,
            section_path=self.section_path,
            page_start=self.page_start,
            page_end=self.page_end,
            content_type=self.content_type,
            extraction_method=self.extraction_method,
            retrieval_score=round(self.retrieval_score, 4),
            text_verbatim=self.text_verbatim,
        )


@dataclass(slots=True)
class GroundedDraft:
    """Intermediate draft response generated by an LLM adapter."""

    answer: str
    is_abstain: bool = False
    abstain_reason: str | None = None
    cited_evidence_ids: list[str] = field(default_factory=list)
    raw_response: str | None = None


@dataclass(slots=True)
class ValidationResult:
    """Deterministic citation and groundedness validation outcome."""

    is_valid: bool
    verified_answer: str
    citations: list[CitationItem] = field(default_factory=list)
    conflicts: list[ConflictItem] = field(default_factory=list)
    unverified_claims: list[str] = field(default_factory=list)
    abstain_reason: str | None = None
